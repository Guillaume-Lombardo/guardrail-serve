package bench

import (
	"fmt"
	"strings"
)

// Markdown renders the result rows as tables, one per corpus, never pooling
// corpora. Rates show num/den and the 95% Wilson interval.
func Markdown(results *Results) string {
	var b strings.Builder
	fmt.Fprintf(&b, "<!-- generated by guardrail-bench report; protocol sha256 %s -->\n\n", results.ProtocolSHA256)
	for _, corpus := range CorpusNames() {
		rows := make([]Row, 0)
		for _, row := range results.Rows {
			if row.Corpus == corpus {
				rows = append(rows, row)
			}
		}
		if len(rows) == 0 {
			continue
		}
		fmt.Fprintf(&b, "### %s\n\n", corpus)
		b.WriteString("| Configuration | Slice | TP | FP | TN | FN | Errors | Recall (95% CI) | FPR (95% CI) | e2e p50 / p95 ms | Latency | Judge share | USD / 1000 req | McNemar p vs ref | D1 |\n")
		b.WriteString("|---|---|---:|---:|---:|---:|---:|---|---|---|---|---|---:|---:|---|\n")
		for _, row := range rows {
			latency := "n/a"
			if row.Latency.N > 0 {
				latency = fmt.Sprintf("%.0f / %.0f", row.Latency.P50, row.Latency.P95)
			}
			judge, cost, mcnemar, d1 := "", "", "", ""
			if row.JudgeFraction != nil {
				judge = fmt.Sprintf("%d/%d", row.JudgeFraction.Num, row.JudgeFraction.Den)
			}
			if row.USDPer1000 != nil {
				cost = fmt.Sprintf("%.4f", *row.USDPer1000)
			}
			if row.VersusRef != nil {
				mcnemar = fmt.Sprintf("%.3f (%d/%d)", row.VersusRef.PValue, row.VersusRef.OnlyA, row.VersusRef.OnlyB)
			}
			if row.D1 != nil {
				d1 = map[bool]string{true: "pass", false: "fail"}[*row.D1]
			}
			errorsCell := fmt.Sprint(row.Counts.Errors)
			if len(row.ErrorKinds) > 0 {
				errorsCell += " (" + strings.Join(row.ErrorKinds, ", ") + ")"
			}
			fmt.Fprintf(&b, "| %s | %s | %d | %d | %d | %d | %s | %s | %s | %s | %s | %s | %s | %s | %s |\n",
				row.Config, row.Slice, row.Counts.TP, row.Counts.FP, row.Counts.TN, row.Counts.FN, errorsCell,
				rate(row.Recall), rate(row.FPR), latency, row.LatencyKind, judge, cost, mcnemar, d1)
		}
		b.WriteString("\n")
	}
	fmt.Fprintf(&b, "Reference: %s, recall %s. D1 allows at most %d false positives on bench-test. Passing: %s. Change default: %v.\n\n",
		results.Decision.Reference, rate(results.Decision.ReferenceRecall), results.Decision.MaxFP,
		orNone(results.Decision.Passing), results.Decision.ChangeDefault)
	fmt.Fprintf(&b, "Paid judge traffic: %d calls, %d input tokens, USD %.6f, %d refused, %d egress blocked, %d failures.\n",
		results.Paid.Calls, results.Paid.InputTokens, results.Paid.CostUSD, results.Paid.Refused, results.Paid.Egress, results.Paid.Failures)
	return b.String()
}

func rate(r Rate) string {
	if !r.Defined {
		return "n/a"
	}
	return fmt.Sprintf("%d/%d = %.1f%% [%.1f, %.1f]", r.Num, r.Den, 100*r.Value, 100*r.Low, 100*r.High)
}

func orNone(values []string) string {
	if len(values) == 0 {
		return "none"
	}
	return strings.Join(values, ", ")
}
